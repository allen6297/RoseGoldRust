pub(super) fn height() -> i32 {
    CELL
}

pub(super) fn width(s: &str) -> i32 {
    if s.is_empty() {
        return 0;
    }
    let mut max = 0i32;
    let mut n = 0i32;
    for unit in s.encode_utf16() {
        if unit == 10 {
            max = max.max(n);
            n = 0;
        } else {
            n += 1;
        }
    }
    max.max(n) * CELL
}

pub(super) fn draw(s: &str, x: i32, y: i32, rgb: u32, mut plot: impl FnMut(i32, i32, u32)) {
    if s.is_empty() {
        return;
    }
    let mut cx = x;
    let mut cy = y;
    for unit in s.encode_utf16() {
        if unit == 10 {
            cx = x;
            cy += CELL + SCALE;
            continue;
        }
        let glyph = glyph(unit);
        for row in 0..8i32 {
            let mut bits = glyph[row as usize];
            for col in 0..8i32 {
                if bits & 0x80 != 0 {
                    for dy in 0..SCALE {
                        for dx in 0..SCALE {
                            plot(cx + col * SCALE + dx, cy + row * SCALE + dy, rgb);
                        }
                    }
                }
                bits = bits.wrapping_shl(1);
            }
        }
        cx += CELL;
    }
}

fn glyph(unit: u16) -> [u8; 8] {
    let code = if (32..=126).contains(&unit) {
        unit
    } else {
        b'?' as u16
    };
    GLYPHS[(code - 32) as usize]
}
